/* --------------------------------------------------------------------------
 * 4. 背景音乐
 *    sources 就是一份"播放列表"：
 *      - 按顺序一首一首往下播；
 *      - 全部播完再从第一首开始（由下面的 loop 控制）；
 *      - 某一首文件缺失或放不出来，会自动跳到下一首，不会报错。
 *
 *    ★ 怎么换成别的歌：把音乐文件放进 public/music/ 目录，
 *      然后改下面 sources 里的文件名即可（建议用英文名，别带空格）。
 * ----------------------------------------------------------------------- */
export const music = {
  /**
   * 播放列表。每一项有两种写法：
   *   'music/track-1.m4a'                      —— 只写文件名
   *   { src: 'music/xxx.m4a', gain: 1.5 }      —— 顺便单独调这一段的音量
   *
   * gain 是"音量倍数"：1 = 原样，1.5 = 比原样大一半。
   * 为什么要它：几段录音是用不同设备、在不同时候录的，响度天然不一样。
   * 与其把音频文件重新压一遍（会损失音质），不如在这里补一点音量 —— 一个比特都不会动到音频本身。
   *
   * 下面这几个数是按实测响度算出来的：以最响的那一首为基准（gain = 1），
   * 其余每一首补到和它一样大声。删掉或增加一首之后，记得重新算一遍。
   */
  sources: [
    { src: 'music/track-2.m4a', gain: 1.25 }, // ← 港中大深圳·上园思廷 5  4:25
    { src: 'music/track-3.m4a', gain: 1.42 }, // ← 港中大深圳·上园思廷 2  3:07
    { src: 'music/track-4.m4a', gain: 1.0 },  // ← 石羊小学 2  3:18（现在它最响，作为基准）
  ],
  volume: 0.55,      // 基础音量 0 ~ 1（上面 gain 是在这个基础上再乘的）
                     // 从 0.45 调到 0.55 是为了补上删掉 track-1 后的整体音量，听起来和之前一样响
  loop: true,        // true = 三首播完一轮，再从第一首开始；false = 播完最后一首就停
  fadeInMs: 2600,    // 点击"打开这封信"之后，第一次响起时的渐入时长（毫秒）
  fadeOutMs: 700,    // 手动暂停时音量渐出的时长（毫秒）
}

