export const qrConfig = {
  // ★★★ 这里改成你的网站地址 ★★★
  url: 'https://your-project.vercel.app',

  // 图片保存位置（相对项目根目录）
  output: 'public/qr-code.png',

  // 同时导出一份矢量 svg（打印更清晰；不需要就设为 ''）
  outputSvg: 'public/qr-code.svg',

  // 图片边长（像素）。1024 已经足够打印，手机扫码也更稳。
  width: 1024,

  // 四周留白。二维码标准要求至少 4，留白太小会扫不出来，不要改小。
  margin: 4,

  // 容错率：L(7%) / M(15%) / Q(25%) / H(30%)
  // H 最抗污损，但也最"密"。保持 H 就很好扫。
  errorCorrectionLevel: 'H',

  // 颜色：保持纯黑白对比度最高，最容易被扫出来
  color: {
    dark: '#000000',
    light: '#FFFFFF',
  },
}

export default qrConfig
